# Encapsulation is the bundling of data (attributes) and methods (functions) that operate on that data into a single unit (class), while restricting direct access to the internal details of an object. It's about hiding the internal state and requiring all interaction to be performed through an object's methods.

# Inheritance is a mechanism where one class (child/subclass) acquires the properties and behaviors of another class (parent/superclass). It establishes an "is-a" relationship and enables code reuse, extensibility, and hierarchical classification.

# Polymorphism (meaning "many forms") is the ability of objects of different classes to respond to the same method call in their own specific way. It allows one interface to be used for a general class of actions, with the specific action determined by the actual object type at runtime.

# Abstraction is the concept of hiding complex implementation details and showing only the essential features of an object. It focuses on what an object does rather than how it does it, providing a simplified interface to the outside world.
